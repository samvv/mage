def is_token(rule: MageRule, visited: set[MageRule] | None = None) -> bool:
    if visited is None:
        visited = set[MageRule]()
    if rule.is_lex:
        # A rule that was explicitly declared a token is always a token
        return True
    if rule.expr is None:
        # If it was not explicitly declared a lexer token, a rule with no
        # expression can never be a token
        return False
    return is_static(rule.expr, visited) and not any(is_token(rule, visited) for rule in referenced(rule.expr))


def static_expr_to_str(expr: MageExpr) -> str:
    if isinstance(expr, MageLitExpr):
        return expr.text
    if isinstance(expr, MageSeqExpr):
        out = ''
        for element in expr.elements:
            out += static_expr_to_str(element)
        return out
    raise RuntimeError(f'could not extract text from {expr}: expression is non-static or not normalised')


def flatten_sequence(expr: MageExpr) -> Iterable[MageExpr]:
    if isinstance(expr, MageSeqExpr):
        for element in expr.elements:
            yield from flatten_sequence(element)
    else:
        yield expr


def flatten_choice(expr: MageExpr) -> Iterable[MageExpr]:
    if isinstance(expr, MageChoiceExpr):
        for element in expr.elements:
            yield from flatten_choice(element)
    else:
        yield expr


@deprecated("we abandonned the idea of compiling list expressions to other constructs")
def make_list_expr(element: MageExpr, separator: MageExpr, min_count = 0) -> MageExpr:
    out = MageSeqExpr([
        element,
        MageRepeatExpr(
            min=max(0, min_count-1),
            max=MAGE_REPEAT_INFINITY,
            expr=MageSeqExpr([
                separator,
                element,
            ])
        )
    ])
    if min_count > 0:
        return out
    return MageChoiceExpr([ out, MageLitExpr('') ])


@deprecated("we abandonned the idea of compiling list expressions to other constructs")
def match_list_expr(expr: MageExpr) -> tuple[MageExpr, MageExpr, int] | None:
    """
    Try to detect a compiled list expression.

    List expressions used to be part of the grammar but are now composed out of
    other constructs.

    This function assumes that the expression has been simplified before this
    function was called. For example, `(a* | a) | ''` will not be detected,
    while `a* | a | ''` will be.
    """
    min_count = 1
    if isinstance(expr, MageChoiceExpr):
        if len(expr.elements) != 2 or not isinstance(expr.elements[1], MageLitExpr) or expr.elements[1].text != '':
            return
        expr = expr.elements[0]
        min_count = 0
    if not (isinstance(expr, MageSeqExpr)
            and len(expr.elements) == 2
            and isinstance(expr.elements[1], MageRepeatExpr)
            and isinstance(expr.elements[1].expr, MageSeqExpr)):
        return
    min_count += expr.elements[1].min
    element = expr.elements[1].expr.elements[1]
    separator = expr.elements[1].expr.elements[0]
    return element, separator, min_count


@lru_cache
def is_keyword(text: str, *, grammar: MageGrammar) -> bool:
    from magelang.eval import accepts, SUCCESS
    if len(text) <= 1:
        return False # single letters are not allowed
    kw = grammar.keyword_rule
    # TODO fall back to a default keyword rule
    return kw is not None and kw.expr is not None and accepts(kw, text) == SUCCESS


@lru_cache
def get_keywords(grammar: MageGrammar) -> list[MageExpr]:
    out = []
    for rule in grammar.rules:
        if rule.expr is not None:
            for expr in get_all_exprs(rule.expr):
                if isinstance(expr, MageLitExpr):
                    if is_keyword(expr.text, grammar=grammar):
                        out.append(expr)
    return out


@cache
def get_char_names() -> dict[str, str]:
    """
    Get a mapping from Unicode characters to longer (snake cased) names. 
    """
    with open(Path(__file__).parent / 'names.json', 'r') as f:
        return json.load(f)


def lit_to_name(text: str, *, grammar: MageGrammar, max_named_chars = DEFAULT_MAX_NAMED_CHARS) -> str | None:
    """
    Find a suitable name for a given string literal, also returning whether the string literal is a pure keyword.

    This function will return `None` in its second element if no suitable name was found.
    """

    names = get_char_names()

    # If it's a single letter
    if len(text) == 1 and text.isalpha():
        # Letters such as 'i' and 'D' are not really keywords
        # They are represented with the lower_ or upper_ prefix
        return f'lower_{text}' if text.islower() else f'upper_{text.lower()}'

    # If the evaluation engine matches it as a keyword
    if is_keyword(text, grammar=grammar):
        return f'{text}_keyword'

    # If the entire word has a predefined name
    if text in names:
        return names[text]

    # Fall back to naming the individual characters
    if len(text) <= max_named_chars:
        return '_'.join(names[ch] for ch in text)

    # It's something long or consists of non-printable characters
    return None

